#!/usr/bin/env python3
"""Lets the Linux build skip flutter_angle's native plugin.

flutter_angle (pulled in by three_js for the STL preview) ships a Linux
plugin that doesn't compile against current Flutter: it targets an older
`FlTextureGL` API and is half commented out, in 0.4.1 and 0.4.2 alike. The
app hides the STL preview on Linux instead (see `stl_preview_widget.dart`),
so the Linux build only needs the Dart side of the package.

This copies the locked flutter_angle out of the pub cache into
`build/linux_overrides/`, drops its `linux:` plugin entry, and writes
`pubspec_overrides.yaml` pointing at the copy. Run it before
`flutter pub get` on Linux builds only; macOS and Windows use the package as
published. The copy isn't committed because the package is ~50 MB of
prebuilt Windows and Android binaries.

Usage (from client/): python3 tool/linux_without_flutter_angle.py
"""

import os
import re
import shutil
import sys
from pathlib import Path

CLIENT = Path(__file__).resolve().parent.parent
COPY = CLIENT / 'build' / 'linux_overrides' / 'flutter_angle'
LINUX_PLUGIN = '      linux:\n        pluginClass: FlutterAnglePlugin\n'


def locked_version() -> str:
    lock = (CLIENT / 'pubspec.lock').read_text()
    m = re.search(r'^  flutter_angle:\n(?:    .*\n)*?    version: "([^"]+)"', lock, re.M)
    if not m:
        sys.exit('flutter_angle is not in pubspec.lock')
    return m.group(1)


def cached_package(version: str) -> Path:
    cache = Path(os.environ.get('PUB_CACHE', Path.home() / '.pub-cache'))
    pkg = cache / 'hosted' / 'pub.dev' / f'flutter_angle-{version}'
    if not pkg.is_dir():
        sys.exit(f'{pkg} not found; run `flutter pub get` first')
    return pkg


def existing_overrides() -> list[str]:
    """The pubspec's own dependency_overrides entries.

    pubspec_overrides.yaml replaces that section rather than merging with
    it, so they have to be carried over.
    """
    pubspec = (CLIENT / 'pubspec.yaml').read_text()
    m = re.search(r'^dependency_overrides:\n((?:[ \t].*\n|\n)*)', pubspec, re.M)
    if not m:
        return []
    return [l for l in m.group(1).splitlines() if l.strip() and not l.strip().startswith('#')]


def main() -> None:
    version = locked_version()
    if COPY.exists():
        shutil.rmtree(COPY)
    shutil.copytree(cached_package(version), COPY, ignore=shutil.ignore_patterns('example'))
    shutil.rmtree(COPY / 'linux')

    spec = COPY / 'pubspec.yaml'
    text = spec.read_text()
    if LINUX_PLUGIN not in text:
        sys.exit(f'flutter_angle {version}: linux plugin entry not found; update this script')
    spec.write_text(text.replace(LINUX_PLUGIN, ''))

    lines = existing_overrides() + [
        '  flutter_angle:',
        f'    path: {COPY.relative_to(CLIENT).as_posix()}',
    ]
    (CLIENT / 'pubspec_overrides.yaml').write_text(
        '# Generated by tool/linux_without_flutter_angle.py for Linux builds.\n'
        'dependency_overrides:\n' + '\n'.join(lines) + '\n'
    )
    print(f'flutter_angle {version} copied without its Linux plugin; run `flutter pub get`')


if __name__ == '__main__':
    main()
